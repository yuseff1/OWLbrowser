// Generates src/components/icons.generated.ts from @fluentui/svg-icons (installed as a desktop dev dependency in the
// repo root; nothing is added to the app). Only the icons listed in scripts/fluent-icons.json are emitted.
// Each icon keeps Fluent's 16 / 20 / 24 px art; <Icon> picks the art drawn for the size it renders at.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const mobile = join(dirname(fileURLToPath(import.meta.url)), '..');
const candidates = [join(mobile, 'node_modules/@fluentui/svg-icons/icons'), join(mobile, '../node_modules/@fluentui/svg-icons/icons')];
const dir = candidates.find(existsSync);
if (!dir) throw new Error('@fluentui/svg-icons not found: run npm install in the repo root');
const { regular, filled } = JSON.parse(readFileSync(join(mobile, 'scripts/fluent-icons.json'), 'utf8'));

function paths(name, size, style) {
  const f = join(dir, `${name.replace(/-/g, '_')}_${size}_${style}.svg`);
  if (!existsSync(f)) return null;
  const svg = readFileSync(f, 'utf8');
  if (/<(?!\/?(svg|path)\b)/.test(svg) || /<path(?![^>]*\bd=)[^>]*>/.test(svg)) throw new Error(`unexpected markup in ${f}`);
  return [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
}

function entry(name, style) {
  const art = {};
  for (const s of [16, 20, 24]) { const p = paths(name, s, style); if (p) art[s] = p; }
  if (!art[20]) throw new Error(`missing ${name} 20 ${style}`);
  return `  '${name}': ${JSON.stringify(art)},`;
}

const reg = [...new Set(regular)].sort();
const fil = [...new Set(filled)].sort();
for (const n of fil) if (!reg.includes(n)) throw new Error(`filled icon ${n} must also be listed in regular`);

const out = `// GENERATED by scripts/gen-icons.mjs from @fluentui/svg-icons (MIT). Do not edit by hand.
export type Art = { 16?: string[]; 20: string[]; 24?: string[] };

export const REGULAR = {
${reg.map((n) => entry(n, 'regular')).join('\n')}
} satisfies Record<string, Art>;

export type IconName = keyof typeof REGULAR;

export const FILLED: Partial<Record<IconName, Art>> = {
${fil.map((n) => entry(n, 'filled')).join('\n')}
};
`;
writeFileSync(join(mobile, 'src/components/icons.generated.ts'), out);
console.log(`icons.generated.ts: ${reg.length} regular, ${fil.length} filled, ${(out.length / 1024).toFixed(1)} KB`);
