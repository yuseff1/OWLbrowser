// Generates src/renderer/lib/ui/icons.generated.ts from @fluentui/svg-icons (dev dependency only).
// Only the icons listed in scripts/fluent-icons.json are emitted, so the bundle carries just what OWL uses.
// Each icon keeps Fluent's 16px art (crisp at 14-16px) and 20px art (used at 17px and up).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'node_modules/@fluentui/svg-icons/icons');
const { regular, filled } = JSON.parse(readFileSync(join(root, 'scripts/fluent-icons.json'), 'utf8'));

function paths(name, size, style) {
  const f = join(dir, `${name.replace(/-/g, '_')}_${size}_${style}.svg`);
  if (!existsSync(f)) return null;
  const svg = readFileSync(f, 'utf8');
  if (/<(?!\/?(svg|path)\b)/.test(svg) || /<path(?![^>]*\bd=)[^>]*>/.test(svg)) throw new Error(`unexpected markup in ${f}`);
  return [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
}

function entry(name, style) {
  const p20 = paths(name, 20, style);
  if (!p20) throw new Error(`missing ${name} 20 ${style}`);
  const p16 = paths(name, 16, style);
  return `  '${name}': ${JSON.stringify(p16 ? { 16: p16, 20: p20 } : { 20: p20 })},`;
}

const reg = [...new Set(regular)].sort();
const fil = [...new Set(filled)].sort();
for (const n of fil) if (!reg.includes(n)) throw new Error(`filled icon ${n} must also be listed in regular`);

const out = `// GENERATED by scripts/gen-icons.mjs from @fluentui/svg-icons (MIT). Do not edit by hand.
type Art = { 16?: string[]; 20: string[] };

export const REGULAR = {
${reg.map((n) => entry(n, 'regular')).join('\n')}
} satisfies Record<string, Art>;

export const FILLED: Partial<Record<keyof typeof REGULAR, Art>> = {
${fil.map((n) => entry(n, 'filled')).join('\n')}
};

export type IconName = keyof typeof REGULAR;
`;
writeFileSync(join(root, 'src/renderer/lib/ui/icons.generated.ts'), out);
console.log(`icons.generated.ts: ${reg.length} regular, ${fil.length} filled`);
